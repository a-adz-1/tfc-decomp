#!/usr/bin/env python3
"""Generate layout checks for classes defined inside .cpp files.

Usage: gen_unit_checks.py <types.h> <decomp_dir> <src_dir> <out_dir>

For every game class (C[A-Z]*) in the pahole dump, finds the compile unit that
defines most of its methods (from decomp/), and writes <out_dir>/<unit>.cpp,
which #includes our src/<unit> and then static_asserts the layout of each
class from that unit. Classes whose unit we don't have yet are listed in
<out_dir>/missing.txt. Classes declared in headers are left to
gen_layout_checks.py.
"""
import glob
import os
import re
import sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(__file__))
from gen_layout_checks import declared, parse  # noqa: E402

HEADER = re.compile(r"^// (C[A-Z]\w*)::")


def class_units(decomp_dir):
    counts = defaultdict(Counter)
    for path in glob.glob(os.path.join(decomp_dir, "**", "*.decomp.c"), recursive=True):
        unit = os.path.relpath(path, decomp_dir)[: -len(".decomp.c")]
        for line in open(path):
            m = HEADER.match(line)
            if m:
                counts[m.group(1)][unit] += 1
    return {c: u.most_common(1)[0][0] for c, u in counts.items()}


def defined_in(src_dir, name):
    """Source file (relative to src_dir) that defines class <name>."""
    pat = re.compile(rf"^\s*(?:class|struct)\s+{name}\b[^;]*$", re.M)
    for sub in ("tfc", "game_shared", "common", "pm_shared"):
        for path in sorted(glob.glob(os.path.join(src_dir, sub, "*.cpp")) + glob.glob(os.path.join(src_dir, sub, "*.h"))):
            if pat.search(open(path, errors="replace").read()):
                return os.path.relpath(path, src_dir)
    return None


def main():
    types_h, decomp_dir, src_dir, out_dir = sys.argv[1:5]
    types = parse(types_h)
    in_headers = declared(os.path.join(src_dir, "tfc"))
    units = class_units(decomp_dir)
    os.makedirs(out_dir, exist_ok=True)
    for old in glob.glob(os.path.join(out_dir, "**", "*.cpp"), recursive=True):
        os.remove(old)

    by_unit, missing = defaultdict(list), []
    for name in sorted(types):
        if not re.match(r"C[A-Z]", name) or name in in_headers:
            continue
        unit = units.get(name)
        if not unit or not os.path.exists(os.path.join(src_dir, unit)):
            # no member functions in the decomp (CTimer, CGhost): find the
            # definition in our source instead
            unit = defined_in(src_dir, name) or unit
        if unit and os.path.exists(os.path.join(src_dir, unit)):
            by_unit[unit].append(name)
        else:
            missing.append((name, unit or "?"))

    for unit, classes in by_unit.items():
        dest = os.path.join(out_dir, unit)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "w") as w:
            w.write("// Generated by tools/gen_unit_checks.py: layout of classes defined in this unit.\n")
            w.write(f'#define private public\n#define protected public\n#include "{os.path.abspath(os.path.join(src_dir, unit))}"\n')
            w.write("#undef offsetof\n#define offsetof(t, m) __builtin_offsetof(t, m)\n")
            for name in classes:
                sz, members = types[name]
                w.write(f'static_assert(sizeof({name}) == {sz}, "LAYOUT {name} size");\n')
                for m, off in members:
                    w.write(f'static_assert(offsetof({name}, {m}) == {off}, "LAYOUT {name} {m}");\n')

    with open(os.path.join(out_dir, "missing.txt"), "w") as w:
        for name, unit in missing:
            w.write(f"{name} {unit}\n")
    n = sum(len(c) for c in by_unit.values())
    print(f"{n} classes in {len(by_unit)} units checked, {len(missing)} in units not written yet")


if __name__ == "__main__":
    main()
