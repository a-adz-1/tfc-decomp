#!/usr/bin/env python3
"""Generate compile-time layout checks from pahole output.

Usage: gen_layout_checks.py <types.h> <src_dir> <out.cpp> <header>...

For every class/struct in the pahole dump that is also declared somewhere in
src_dir's headers, emits static_asserts for sizeof() and each direct member's
offsetof(). Compiling the output against our headers then reports exactly
which classes and members don't match the original binary.
"""
import glob
import os
import re
import sys

START = re.compile(r"^(?:class|struct) (\w+)(?: : [^{]+)? \{")
MEMBER = re.compile(r"^\t(?!/\*)(.+?)(\w+)(\[\d+\])*;\s+/\*\s+(\d+)\s+(\d+) \*/")
SIZE = re.compile(r"/\* size: (\d+),")


def parse(path):
    types = {}
    name = size = None
    for line in open(path):
        if name is None:
            m = START.match(line)
            if m:
                name, members, depth, size = m.group(1), [], 0, None
            continue
        depth += line.count("{") - line.count("}")
        if depth < 0:  # closing brace of the type
            depth = 0
        if line.startswith("}"):
            if size is not None and name not in types:
                types[name] = (size, members)
            name, size = None, None
            continue
        if depth == 0:
            m = MEMBER.match(line)
            if m and "static" not in m.group(1) and "_vptr" not in line and ":" not in line.split(";")[0]:
                members.append((m.group(2), int(m.group(4))))
        m = SIZE.search(line)
        if m:
            size = int(m.group(1))
    return types



def declared(src_dir):
    names = set()
    for h in glob.glob(os.path.join(src_dir, "**", "*.h"), recursive=True):
        for m in re.finditer(r"^\s*(?:class|struct)\s+(\w+)\s*(?::[^;{]*)?\{", open(h, errors="replace").read(), re.M):
            names.add(m.group(1))
    return names


def main():
    types_h, src_dir, out, headers = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4:]
    types = parse(types_h)
    ours = declared(src_dir)
    with open(out, "w") as w:
        w.write("// Generated by tools/gen_layout_checks.py from the original binary's DWARF.\n")
        w.write("// Every static_assert here must pass for the layouts to match tfc.so.\n")
        w.write("#include <stddef.h>\n#define private public\n#define protected public\n")
        for h in headers:
            w.write(f'#include "{h}"\n')
        w.write("#undef offsetof\n#define offsetof(t, m) __builtin_offsetof(t, m)\n\n")
        n = 0
        for name in sorted(types):
            if name not in ours or name.startswith("_"):
                continue
            sz, members = types[name]
            w.write(f'static_assert(sizeof({name}) == {sz}, "LAYOUT {name} size");\n')
            for m, off in members:
                w.write(f'static_assert(offsetof({name}, {m}) == {off}, "LAYOUT {name} {m}");\n')
            n += 1
        print(f"{n} classes checked ({len(types)} in binary, {len(ours)} declared in src)")


if __name__ == "__main__":
    main()
